#!/usr/bin/env python3
"""Fold the voice's line times and the score's beat grid into one file the page can read.

The page is loaded from disk by the renderer, so it can't fetch JSON next to it.
It gets a plain script instead.

    python3 make_timings.py   ->  timings.js
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))

lines = json.load(open(os.path.join(HERE, 'lines.json')))
beats = json.load(open(os.path.join(HERE, 'beats.json')))

data = {
    'duration': round(max(lines['duration'], beats['duration']), 3),
    'bpm': beats['bpm'],
    'beat': beats['beat'],
    'lines': [{'start': l['start'], 'end': l['end']} for l in lines['lines']],
}

with open(os.path.join(HERE, 'timings.js'), 'w') as f:
    f.write('// generated by make_timings.py - do not edit\n')
    f.write('window.KS = ' + json.dumps(data, indent=2) + '\n')

print(f"timings.js  {len(data['lines'])} lines, {data['duration']}s, {data['bpm']} BPM")
